import fs from 'node:fs';
import path from 'node:path';
import { projectsDir, worktreesDir } from './config.js';
import { PROJECT_ID_RE } from './util.js';
import { db } from './db/index.js';
import type { ProjectMeta } from './db/types.js';

/**
 * Per-owner storage limit. Off by default: only enforced when
 * ALDINE_STORAGE_QUOTA_MB is set, and only for projects that have an owner
 * (with accounts off nobody owns a project, so nothing is limited).
 *
 * What counts for an owner is every file of every project they own, trashed
 * ones too until the trash is emptied or purged: the repository directory
 * (main's working files and `.git`, which holds the history of every branch)
 * and the worktrees of the other branches. Typeset output (`.aldine-out`) is
 * not counted: it is regenerated by the next typeset. Sizes are file sizes,
 * not allocated blocks, so the figure is the same on every filesystem.
 *
 * Over the limit nothing is deleted and nobody is locked out: collaborative
 * editing never consults it, and a text write that grows a file by at most
 * EDIT_ALLOWANCE_BYTES is never refused. What grows storage substantially
 * (uploads, imports, new projects, duplicates, new branches, pulls) is
 * refused with HTTP 402, like an exhausted typeset budget (usage.ts).
 *
 * Sizes are cached per project and per process. A write through the store or
 * the repository lock marks the project for a recount on its next read, and
 * a count older than RECOUNT_MS is redone, which also catches writes made by
 * another node. A check walks only the projects of one owner that changed.
 */

const MB = 1024 * 1024;

/** A text write that grows storage by no more than this always goes through. */
export const EDIT_ALLOWANCE_BYTES = 64 * 1024;

const RECOUNT_MS = 60 * 60 * 1000;

/** The instance-wide limit in bytes, or 0 for none. */
export function storageQuotaBytes(): number {
  const mb = Number(process.env.ALDINE_STORAGE_QUOTA_MB || 0);
  return Number.isFinite(mb) && mb > 0 ? Math.round(mb * MB) : 0;
}

/**
 * The storage limit of one owner in bytes, 0 for none. Every check goes
 * through here: a per-account plan, or an organisation that owns projects,
 * supplies its own number in this function and nowhere else.
 */
export async function storageLimitFor(ownerId: string): Promise<number> {
  if (!ownerId) return 0;
  return storageQuotaBytes();
}

const counted = new Map<string, { bytes: number; at: number }>();
const changed = new Set<string>();
const counting = new Map<string, Promise<number>>();

/** The project's files changed: the next read counts it again. */
export function noteStorageChanged(projectId: string): void {
  changed.add(projectId);
}

/** The project is gone: drop its count. */
export function forgetProjectStorage(projectId: string): void {
  counted.delete(projectId);
  changed.delete(projectId);
}

const SKIPPED = new Set(['.aldine-out', '.papyr-out']);

async function treeBytes(dir: string): Promise<number> {
  let entries: fs.Dirent[];
  try { entries = await fs.promises.readdir(dir, { withFileTypes: true }); } catch { return 0; }
  const sizes = await Promise.all(entries.map(async (e) => {
    if (SKIPPED.has(e.name)) return 0;
    const abs = path.join(dir, e.name);
    if (e.isDirectory()) return treeBytes(abs);
    if (!e.isFile()) return 0;
    try { return (await fs.promises.lstat(abs)).size; } catch { return 0; }
  }));
  return sizes.reduce((a, b) => a + b, 0);
}

/** Bytes one project occupies (see the module comment for what counts). */
export async function projectStorageBytes(projectId: string, now = Date.now()): Promise<number> {
  if (!PROJECT_ID_RE.test(projectId)) return 0;
  const known = counted.get(projectId);
  if (known && !changed.has(projectId) && now - known.at < RECOUNT_MS) return known.bytes;
  const running = counting.get(projectId);
  if (running) return running;
  // Cleared before the walk, so a write during it marks the project again.
  changed.delete(projectId);
  const count = (async () => {
    const bytes = (await treeBytes(path.join(projectsDir, projectId))) + (await treeBytes(path.join(worktreesDir, projectId)));
    counted.set(projectId, { bytes, at: Date.now() });
    return bytes;
  })().finally(() => counting.delete(projectId));
  counting.set(projectId, count);
  return count;
}

async function sumOwned(metas: ProjectMeta[], ownerId: string): Promise<number> {
  let total = 0;
  for (const m of metas) if (m.ownerId === ownerId) total += await projectStorageBytes(m.id);
  return total;
}

/** Bytes the projects of one owner occupy, trashed ones included. */
export async function ownerStorageBytes(ownerId: string): Promise<number> {
  return sumOwned(await db().listMeta(), ownerId);
}

/** Bytes per owner, for every owner with a project. */
export async function storageByOwner(): Promise<Map<string, number>> {
  const out = new Map<string, number>();
  for (const m of await db().listMeta()) {
    if (!m.ownerId) continue;
    out.set(m.ownerId, (out.get(m.ownerId) || 0) + await projectStorageBytes(m.id));
  }
  return out;
}

/** What `/api/usage` and account settings show: limitBytes 0 means none. */
export async function storageUsageFor(ownerId: string): Promise<{ usedBytes: number; limitBytes: number }> {
  const limitBytes = await storageLimitFor(ownerId);
  return { usedBytes: await ownerStorageBytes(ownerId), limitBytes };
}

/** "0.4 MB", "7.5 MB", "512 MB": one decimal below 10 MB, whole numbers above. */
export function formatMb(bytes: number): string {
  const mb = bytes / MB;
  if (mb >= 10) return `${Math.round(mb)} MB`;
  const r = Math.round(mb * 10) / 10;
  return `${r === 0 && bytes > 0 ? 0.1 : r} MB`;
}

export type StorageAction = 'upload' | 'import' | 'create' | 'copy' | 'branch' | 'pull' | 'write';
const ACTIONS: Record<StorageAction, { again: string; needs: string }> = {
  upload: { again: 'upload again', needs: 'This upload needs' },
  import: { again: 'import again', needs: 'This import needs' },
  create: { again: 'create projects again', needs: 'The new project needs' },
  copy: { again: 'duplicate projects again', needs: 'The copy needs' },
  branch: { again: 'create branches again', needs: 'The new branch needs' },
  pull: { again: 'pull again', needs: 'This pull needs' },
  write: { again: 'save large changes again', needs: 'This change needs' },
};

/**
 * The sentence a refusal carries. `self`: the person asking owns the
 * storage; otherwise they are told whose it is and what they can do about
 * it themselves (delete files of this project) and what only the owner can.
 */
export function storageMessage(o: { usedBytes: number; limitBytes: number; incomingBytes: number; action: StorageAction; self: boolean; ownerName?: string }): string {
  const a = ACTIONS[o.action];
  const owner = o.ownerName ? `this project's owner, ${o.ownerName},` : "this project's owner";
  const fix = o.self
    ? 'Delete files or projects, or empty the trash,'
    : 'Delete files from this project, or ask the owner to delete projects or empty their trash,';
  if (o.usedBytes >= o.limitBytes) {
    return o.self
      ? `You have used ${formatMb(o.usedBytes)} of your ${formatMb(o.limitBytes)}. ${fix} to ${a.again}.`
      : `${owner[0].toUpperCase()}${owner.slice(1)} has used ${formatMb(o.usedBytes)} of ${formatMb(o.limitBytes)}. ${fix} to ${a.again}.`;
  }
  const left = formatMb(o.limitBytes - o.usedBytes);
  return o.self
    ? `${a.needs} ${formatMb(o.incomingBytes)}, and you have ${left} of your ${formatMb(o.limitBytes)} left. ${fix} to make room.`
    : `${a.needs} ${formatMb(o.incomingBytes)}, and ${owner} has ${left} of ${formatMb(o.limitBytes)} left. ${fix} to make room.`;
}

export interface StorageRefusal {
  error: string;
  storageExceeded: true;
  storage: { usedBytes: number; limitBytes: number };
}

/**
 * Null when `incomingBytes` more fit the limit of `ownerId`, else the
 * refusal to answer with HTTP 402. `viewerId` is the person asking: the
 * sentence speaks to them as the owner, or names the owner they need to ask.
 * An operation whose size is not known in advance passes 0: it is refused
 * only once the limit is reached, and may overshoot it by that one operation.
 */
export async function storageRefusal(ownerId: string | undefined, viewerId: string | undefined, incomingBytes: number, action: StorageAction): Promise<StorageRefusal | null> {
  if (!ownerId) return null;
  const limitBytes = await storageLimitFor(ownerId);
  if (!limitBytes) return null;
  const usedBytes = await ownerStorageBytes(ownerId);
  const incoming = Math.max(0, incomingBytes);
  if (usedBytes < limitBytes && usedBytes + incoming <= limitBytes) return null;
  const self = viewerId === ownerId;
  const ownerName = self ? undefined : (await db().getUser(ownerId).catch(() => null))?.name;
  return {
    error: storageMessage({ usedBytes, limitBytes, incomingBytes: incoming, action, self, ownerName }),
    storageExceeded: true,
    storage: { usedBytes, limitBytes },
  };
}
